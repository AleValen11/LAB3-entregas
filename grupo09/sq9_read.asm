; LAB 3 - GRUPO 09 - Lectura decimal independiente.
; Acepta: enteros 0..32767, punto decimal opcional con hasta 4 digitos.
; Devuelve R0:entero R1:fraccion binaria Q15.16, R2:estado.
; Estado: 0=OK; 1=invalido; 2=negativo; 3=fuera de rango; 4=salir (q).
; No usa rutinas externas; preserva R3,R4,R5,R7. No reentrante.
SQ9_READ_DQ16
    ST R3 SQI_SAVE3
    ST R4 SQI_SAVE4
    ST R5 SQI_SAVE5
    ST R7 SQI_SAVE7
    AND R0 R0 #0
    ST R0 SQI_INTEGER
    ST R0 SQI_FRAC_NUM
    ST R0 SQI_DOT_SEEN
    ST R0 SQI_FRAC_DIGITS
    ST R0 SQI_ANY_DIGIT
    ST R0 SQI_ERR
    ADD R0 R0 #1
    ST R0 SQI_FRAC_DEN
SQI_READ_CHAR
    GETC
    ST R0 SQI_CHAR
    ADD R4 R0 #-10
    BRz SQI_END_LINE
    ADD R4 R0 #-13
    BRz SQI_END_LINE
    OUT
    LD R0 SQI_CHAR
    LD R4 SQI_NEG_ASCII_DOT
    ADD R4 R0 R4
    BRz SQI_DECIMAL_POINT
    LD R4 SQI_NEG_ASCII_MINUS
    ADD R4 R0 R4
    BRz SQI_NEGATIVE
    LD R4 SQI_NEG_ASCII_Q
    ADD R4 R0 R4
    BRz SQI_QUIT
    LD R4 SQI_NEG_ASCII_ZERO
    ADD R5 R0 R4               ; R5 = digito 0..9
    BRn SQI_INVALID
    ADD R4 R5 #-10
    BRzp SQI_INVALID
    LD R4 SQI_ANY_DIGIT
    ADD R4 R4 #1
    ST R4 SQI_ANY_DIGIT
    LD R4 SQI_DOT_SEEN
    BRp SQI_FRACTION_DIGIT
SQI_INTEGER_DIGIT
    LD R1 SQI_INTEGER
    LD R4 SQI_MINUS3276
    ADD R4 R1 R4
    BRp SQI_RANGE
    BRn SQI_INTEGER_MUL10
    ADD R4 R5 #-7
    BRp SQI_RANGE
SQI_INTEGER_MUL10
    ADD R4 R1 R1
    ADD R1 R4 R4
    ADD R1 R1 R1
    ADD R1 R1 R4
    ADD R1 R1 R5
    ST R1 SQI_INTEGER
    BRnzp SQI_READ_CHAR
SQI_FRACTION_DIGIT
    LD R4 SQI_FRAC_DIGITS
    ADD R4 R4 #1
    ST R4 SQI_FRAC_DIGITS
    ADD R1 R4 #-4
    BRp SQI_INVALID
    LD R1 SQI_FRAC_NUM
    ADD R4 R1 R1
    ADD R1 R4 R4
    ADD R1 R1 R1
    ADD R1 R1 R4
    ADD R1 R1 R5
    ST R1 SQI_FRAC_NUM
    LD R1 SQI_FRAC_DEN
    ADD R4 R1 R1
    ADD R1 R4 R4
    ADD R1 R1 R1
    ADD R1 R1 R4
    ST R1 SQI_FRAC_DEN
    BRnzp SQI_READ_CHAR
SQI_DECIMAL_POINT
    LD R4 SQI_DOT_SEEN
    BRp SQI_INVALID
    ADD R4 R4 #1
    ST R4 SQI_DOT_SEEN
    BRnzp SQI_READ_CHAR
SQI_END_LINE
    LD R4 SQI_ANY_DIGIT
    BRz SQI_INVALID_EOL
    AND R0 R0 #0
    ADD R0 R0 #10
    OUT
    LD R1 SQI_FRAC_NUM
    LD R3 SQI_FRAC_DEN
    AND R2 R2 #0
    LD R4 SQI_SIXTEEN
; Dividir binariamente frac_numerador / denominador y extraer 16 bits.
; En cada paso resto*2 <= 19998: la resta con signo es segura.
SQI_DIV_LOOP
    ADD R1 R1 R1
    ADD R2 R2 R2
    NOT R5 R3
    ADD R5 R5 #1
    ADD R5 R1 R5
    BRn SQI_DIV_SKIP
    ADD R1 R5 #0
    ADD R2 R2 #1
SQI_DIV_SKIP
    ADD R4 R4 #-1
    BRp SQI_DIV_LOOP
    ADD R1 R2 #0
    LD R0 SQI_INTEGER
    AND R2 R2 #0
    BRnzp SQI_RETURN
SQI_INVALID_EOL
    AND R2 R2 #0
    ADD R2 R2 #1
    ST R2 SQI_ERR
    BRnzp SQI_INVALID_RETURN
SQI_INVALID
    AND R2 R2 #0
    ADD R2 R2 #1
    BRnzp SQI_DRAIN
SQI_NEGATIVE
    AND R2 R2 #0
    ADD R2 R2 #2
    BRnzp SQI_DRAIN
SQI_RANGE
    AND R2 R2 #0
    ADD R2 R2 #3
    BRnzp SQI_DRAIN
SQI_QUIT
    LD R4 SQI_ANY_DIGIT
    BRp SQI_INVALID
    LD R4 SQI_DOT_SEEN
    BRp SQI_INVALID
    AND R2 R2 #0
    ADD R2 R2 #4
SQI_DRAIN
    ST R2 SQI_ERR
SQI_DRAIN_LOOP
    GETC
    ADD R4 R0 #-10
    BRz SQI_INVALID_RETURN
    ADD R4 R0 #-13
    BRz SQI_INVALID_RETURN
    OUT
    BRnzp SQI_DRAIN_LOOP
SQI_INVALID_RETURN
    AND R0 R0 #0
    ADD R0 R0 #10
    OUT
    AND R0 R0 #0
    AND R1 R1 #0
    LD R2 SQI_ERR
    BRnzp SQI_RETURN
SQI_RETURN
    LD R3 SQI_SAVE3
    LD R4 SQI_SAVE4
    LD R5 SQI_SAVE5
    LD R7 SQI_SAVE7
    RET
SQI_NEG_ASCII_ZERO .FILL #-48
SQI_NEG_ASCII_DOT .FILL #-46
SQI_NEG_ASCII_MINUS .FILL #-45
SQI_NEG_ASCII_Q .FILL #-113
SQI_MINUS3276 .FILL #-3276
SQI_SIXTEEN .FILL #16
SQI_SAVE3 .BLKW #1
SQI_SAVE4 .BLKW #1
SQI_SAVE5 .BLKW #1
SQI_SAVE7 .BLKW #1
SQI_CHAR .BLKW #1
SQI_INTEGER .BLKW #1
SQI_FRAC_NUM .BLKW #1
SQI_FRAC_DEN .BLKW #1
SQI_FRAC_DIGITS .BLKW #1
SQI_ANY_DIGIT .BLKW #1
SQI_DOT_SEEN .BLKW #1
SQI_ERR .BLKW #1
.END
